/**
 * 按筛选条件查询 Mock 调用日志
 */
export async function queryMockCallLogs(query: CallLogQuery): Promise<PageResult<CallLogItem>> {
    await waitMock()

    const keyword = query.keyword.trim().toLowerCase()
    const filtered = MOCK_CALL_LOGS.filter((item) => {
        if (keyword) {
            const haystack = `${item.traceId} ${item.apiKeyName} ${item.apiKeyValue}`.toLowerCase()
            if (!haystack.includes(keyword))
                return false
        }
        if (query.model && item.model !== query.model)
            return false
        if (query.status && item.status !== query.status)
            return false
        if (!matchLogBillingFilter(item, query.billingMode))
            return false
        if (query.range) {
            const day = item.time.slice(0, 10)
            if (day < query.range[0] || day > query.range[1])
                return false
        }
        return true
    })

    const start = (query.page - 1) * query.pageSize
    return {
        list: filtered.slice(start, start + query.pageSize),
        total: filtered.length,
        page: query.page,
        pageSize: query.pageSize,
    }
}
